from __future__ import annotations

import os
import subprocess
from pathlib import Path

import pytest

from scripts.check_repo_hygiene import commit_violations, find_violations


def test_rejects_handoff_filename(tmp_path: Path) -> None:
    path = Path("docs/handoff-example.md")
    (tmp_path / path).parent.mkdir(parents=True)
    (tmp_path / path).write_text("session state\n")
    assert find_violations(tmp_path, [path]) == [
        "docs/handoff-example.md: prohibited handoff file"
    ]


@pytest.mark.parametrize("term", ["co" + "dex", "clau" + "de", "github " + "copilot"])
def test_rejects_coding_tool_name(tmp_path: Path, term: str) -> None:
    path = Path("module.py")
    (tmp_path / path).write_text("# generated by " + term.upper() + "\n")
    assert find_violations(tmp_path, [path]) == [
        "module.py:1: prohibited coding-tool name"
    ]


